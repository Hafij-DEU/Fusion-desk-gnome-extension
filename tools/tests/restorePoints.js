// Restore point checks: gjs -m restorePoints.js REPO_DIR TEMP_DIR (run-tests.sh does this).
import Gio from 'gi://Gio';
import GLib from 'gi://GLib';
import System from 'system';
const ARGV = System.programArgs;
const RP = await import('file://' + ARGV[0] + '/lib/restorePoints.js');
const src = Gio.SettingsSchemaSource.new_from_directory(ARGV[1] + '/schemas', null, false);
const s = new Gio.Settings({settings_schema: src.lookup('org.gnome.shell.extensions.fusion-desk', false)});
const ok = (c, m) => { print((c ? 'PASS ' : 'FAIL ') + m); if (!c) System.exit(1); };
s.set_int('panel-height', 40); s.set_string('glass-style', 'PLANNER');
const p = RP.createPoint(s, 'Test point');
ok(RP.listPoints().length === 1, 'point listed');
s.set_int('panel-height', 70); s.set_string('glass-style', 'SMOKE');
GLib.file_set_contents(ARGV[1] + '/cfg/harbor/glass-global', 'effect=OFF\n');
GLib.file_set_contents(ARGV[1] + '/cfg/harbor/glass-astra', 'style=GEL\n');
const r = RP.restorePoint(s, RP.listPoints().find(x => !x.auto));
Gio.Settings.sync();
ok(r.failed === 0, 'no failures');
ok(s.get_int('panel-height') === 40 && s.get_string('glass-style') === 'PLANNER', 'settings back');
ok(new TextDecoder().decode(GLib.file_get_contents(ARGV[1] + '/cfg/harbor/glass-global')[1]).includes('PLANNER'), 'glass-global back');
ok(new TextDecoder().decode(GLib.file_get_contents(ARGV[1] + '/cfg/harbor/glass-astra')[1]) === 'global\n', 'new per-app file set to global');
ok(r.undo && r.undo.auto && r.undo.label === 'Before restore', 'undo point made');
RP.restorePoint(s, r.undo); Gio.Settings.sync();
ok(s.get_int('panel-height') === 70, 'undo works');
for (let i = 0; i < 20; i++) RP.autoPoint(s, 'auto ' + i);
ok(RP.listPoints().filter(x => x.auto).length === 15, 'autos pruned to 15');
ok(RP.listPoints().some(x => x.label === 'Test point'), 'own point kept');
GLib.file_set_contents(ARGV[1] + '/cfg/fusion-desk/restore-points/99999999-bad.json', '{broken');
ok(RP.listPoints().length === 16, 'broken file skipped');
RP.dailyPoint(s); RP.dailyPoint(s);
ok(RP.listPoints().filter(x => x.label === 'Daily').length === 1, 'daily once');
const bad = {...p, keys: {...p.keys, 'panel-height': '9999'}};
ok(RP.restorePoint(s, bad).failed === 1, 'out-of-range counted');
ok(RP.removePoint(RP.listPoints().find(x => !x.auto)), 'remove');
const own = RP.listPoints().find(x => !x.auto) ?? RP.createPoint(s, 'Export me');
RP.exportPoint(own, ARGV[1] + '/exported.json');
const imp = RP.importPoint(ARGV[1] + '/exported.json');
ok(imp.label.endsWith('(imported)') && !imp.auto && RP.listPoints().some(x => x.path === imp.path), 'export + import');
GLib.file_set_contents(ARGV[1] + '/junk.json', '{"hello": 1}');
let threw = false;
try { RP.importPoint(ARGV[1] + '/junk.json'); } catch { threw = true; }
ok(threw, 'import rejects a foreign file');
